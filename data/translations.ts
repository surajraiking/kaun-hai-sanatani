export type Language = 'en' | 'hi';

export function localizeQuestion(question: Question, language: Language): Question {
  if (language === 'en') return question;
  const baseId = question.id.split('-r')[0];
  const content = HINDI_CONTENT[baseId];
  if (!content) return question;
  return { ...question, ...content, prompt: content.prompt };
}
